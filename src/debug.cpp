/****************************************************************************************************************************/

void logGPSInfo(const GPSInfo &p)
{
    if (CORE_DEBUG_LEVEL < ARDUHAL_LOG_LEVEL_INFO)
        return;

    char buf[32];
    struct tm tt;
    gmtime_r(&p.gpstime, &tt);
    strftime(buf, sizeof(buf), "%Tutc", &tt);
    log_i("#% 3lu %s Sat:% 2u Lat: %.5f Lon: %.5f   %.1f km/h Fix: %c Age: %u",
          p.sentences, buf, p.satellites, (double)p.point.lat, (double)p.point.lon, (double)p.speed, (char)p.quality + '0', p.age);
}

